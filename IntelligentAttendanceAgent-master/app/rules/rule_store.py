RULE_TYPE_LIST = sorted({r.rule_type for r in RULES if r.rule_type != "裁定"})


def select_by_keywords(text: str) -> list[str]:
    """关键词快匹配，返回命中的 rule_type。"""
    hit = set()
    for r in RULES:
        if r.rule_type == "裁定":
            continue
        for kw in r.keywords:
            if kw and kw in text:
                hit.add(r.rule_type)
    return sorted(hit)


def get_rules(rule_types: list[str], include_verdicts: bool = True) -> str:
    """按类型取规则内容；裁定类默认并入（单一事实源）。"""
    chosen = [r for r in RULES if r.rule_type in rule_types]
    if include_verdicts:
        chosen += [r for r in RULES if r.rule_type == "裁定"]
    if not chosen:
        # 未命中时兜底：返回全部非裁定规则，避免无上下文
        chosen = [r for r in RULES if r.rule_type != "裁定"]
    lines = [f"- [{r.rule_type}] {r.title}：{r.content}" for r in chosen]
    return "\n".join(lines)
